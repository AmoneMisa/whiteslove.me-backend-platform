export function normalizeLanguage(value) {
  return String(value || '').toLowerCase().startsWith('en') ? 'en' : 'ru';
}

export function t(language, key) {
  const lang = normalizeLanguage(language);
  return messages[lang][key] ?? messages.ru[key] ?? key;
}

export function kindLabel(language, kind) {
  if (kind === 'flats') return t(language, 'apartments');
  if (kind === 'jobs') return t(language, 'jobs');
  return t(language, 'candidates');
}
